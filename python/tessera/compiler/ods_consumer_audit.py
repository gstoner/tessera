"""Decision #29's op-level clause: does every declared ODS op have a consumer?

GOV-ODS-CONSUMER-1 (docs/audit/compiler/INTEGRATED_COMPILER_PLAN.md). Decision
#29 says a declared ODS op must be consumed by a named pass or code path, or be
deleted. This module is the scan behind `tests/unit/test_ods_op_has_consumer.py`:
it parses every op declared in the Tessera `.td` files under `src/` (archive
excluded) and classifies each one by the strongest place it is referenced.

**Parsing.** TableGen cannot be parsed by one regex, and the first version of
this gate proved it: its pattern only matched `def X : Op<Dialect, "name">`, so
the dominant form -- `def X : Dialect_Op<"name", [...]>` through a class
template -- was silently skipped (its regex matches 286 of 623 op records, measured
2026-09-27).
This parser reads `class` and `def` records with balanced `<...>` argument
lists, binds each class's template parameters, and walks the base chain until
it reaches `Op<Dialect, mnemonic, ...>`. It was cross-checked op-for-op against
`llvm-tblgen --dump-json` when it landed; `test_ods_op_has_consumer.py` pins
known ops and a synthetic `.td` so a regression in either direction fails.

**What counts as a reference.**

* ``compiler`` -- the op is named by shipped compiler code: C++ (`.cpp`/`.h`/
  `.inc`/`.td` other than its own `.td`) under `src/` or `tools/`, or Python
  under `python/tessera/`. A C++ reference is the generated class name as an
  identifier (`builder.create<FooOp>`, `OpRewritePattern<FooOp>`,
  `isa<FooOp>`, `FooOp::create(...)`), the TableGen record name (DRR
  patterns), or the full `dialect.mnemonic` used *as IR* inside a string
  literal. A Python reference is the same, in a string that is not a
  docstring. "As IR" means the string is exactly the name, or the name starts
  a line or follows `= `, `"` or `(`, and is followed by `(`, `%`, `{`, `<`,
  `:`, `[`, `"`, a newline or the end -- so `"tessera.foo"` and
  `%0 = tessera.foo %a` count and a sentence that mentions `tessera.foo.`
  does not.
* ``fixture_only`` -- the op is named only by tests: lit `.mlir` fixtures,
  anything under a `test`/`tests` directory, and unit tests. **A fixture alone
  does not satisfy #29.** A fixture proves the op parses and verifies; #29
  asks for a consumer *in the compiler*, and an op that only a hand-written
  fixture ever constructs is exactly the closed-looking contract carrying
  nothing that the decision exists to catch.
* ``unreferenced`` -- nothing outside its own `.td` names it.

**What does not count.** The op's own `.td`; generated code (build trees;
only git-tracked files are read when the root is a checkout); comments (`//`
in C++/TableGen, `#` and docstrings in Python); the dialect's own
implementation files -- a file that includes a generated `*.cpp.inc` and
defines members of a dialect's op classes (`LogicalResult FooOp::verify()`)
implements that dialect, and its arity tables, verifiers and builders are the
declaration's implementation, not a consumer of it; and the name registries
in :data:`REGISTRY_MODULES`, which list names rather than produce or consume
IR. A C++ class name qualified by a foreign namespace (`scf::YieldOp`), or
bare in a file that imports it with `using mlir::func::FuncOp;` or that says
`using namespace` for an upstream dialect, is not a reference to a Tessera op
of that name; and a class name generated by two Tessera dialects (ODS strips
the record prefix, so `Cache_RingCreateOp` and `Tessera_RingCreateOp` both
yield `RingCreateOp`) counts only when qualified by the owning namespace.
These rules are meant to fail closed -- to call a consumed op unconsumed
rather than the reverse -- and each hole found in review
(`tessera_nvidia.func` vouched for by `using mlir::func::FuncOp`, prose in a
`reason=` string, an op's own shape table) is pinned by a test.

**Known limit.** A name assembled at run time (`f"tessera_rocm.{kind}"`) is
invisible to any static scan; such an op reads as `fixture_only` or
`unreferenced` and its waiver must say so.
"""

