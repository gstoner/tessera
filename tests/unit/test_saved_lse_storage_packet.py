"""Consumer gates for the exact-device saved-LSE storage evidence."""
from pathlib import Path
import gzip
import hashlib
import json
import math
import xml.etree.ElementTree as ET

import pytest
from tessera import runtime as rt

ROOT = Path(__file__).resolve().parents[2]
PACKET = ROOT / "benchmarks/baselines/sm120_saved_lse_storage_20261016"
BENCHMARK = json.loads((PACKET / "benchmark/packet.json").read_text())


@pytest.mark.parametrize("row", BENCHMARK["rows"], ids=lambda row: row["artifact"])
def test_saved_storage_binary_metadata_and_timing_scopes(row):
    artifact = rt.RuntimeArtifact.from_json(gzip.decompress(
        (PACKET / "benchmark" / row["artifact"]).read_bytes()).decode())
    descriptor = artifact.launch_descriptor
    assert descriptor.abi_id == row["abi"]
    assert descriptor.entry_symbol == row["entry"]
    assert descriptor.descriptor_digest == row["descriptor_digest"]
    assert artifact.native_image.image_digest == row["image_digest"]
    assert descriptor.provenance["row_lse"] == "f32[B,Hq,Sq]"
    assert descriptor.buffers[-1].dtype == "fp32" and descriptor.buffers[-1].rank == 3
    for field in ("public_completed_call_samples_ms", "native_kernel_event_samples_ms"):
        assert set(row[field]) == {"host", "resident"}
        for samples in row[field].values():
            assert len(samples) == 15
            assert all(math.isfinite(value) and value > 0 for value in samples)
    assert len(row["stages"]) == 5
    for left, right in zip(row["stages"][:-1], row["stages"][1:], strict=True):
        assert left["output_digest"] == right["input_digest"]


def test_saved_storage_source_device_and_compiler_free_replay():
    helper = gzip.decompress((PACKET / "helpers/capture_fp32_controls.py.gz").read_bytes())
    for folder in ("fp32-before", "fp32-after"):
        control = json.loads((PACKET / "controls" / folder / "index.json").read_text())
        assert hashlib.sha256(helper).hexdigest() == control["source_before"]["helper_sha256"]
    assert BENCHMARK["source_before"] == BENCHMARK["source_after"]
    assert not BENCHMARK["source_before"]["status"]
    assert "RTX 5070" in BENCHMARK["device"]
    assert "GPU-cba12639-821a-7a10-4cd3-f918f9c0a545" in BENCHMARK["device"]
    assert BENCHMARK["device"].split(",")[2].strip() == "12.0"
    replay = json.loads((PACKET / "benchmark/replay.json").read_text())
    assert replay["compiler_subprocesses_forbidden"] is True
    assert {row["artifact"] for row in replay["rows"]} == {
        row["artifact"] for row in BENCHMARK["rows"]}
    assert all(row["execution_kind"] == "native_gpu" for row in replay["rows"])
    source = json.loads((PACKET / "validation/source-manifest.json").read_text())
    for name, digest in source["files"].items():
        assert hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == digest, name


@pytest.mark.parametrize("index", range(12))
def test_saved_storage_legacy_fp32_controls_remain_byte_identical(index):
    before = json.loads((PACKET / "controls/fp32-before/index.json").read_text())
    after = json.loads((PACKET / "controls/fp32-after/index.json").read_text())
    left, right = before["rows"][index], after["rows"][index]
    for key in ("case", "entry", "abi", "tile_sha256", "target_sha256", "ptx_sha256"):
        assert left[key] == right[key]
    for folder, row in (("fp32-before", left), ("fp32-after", right)):
        artifact = rt.RuntimeArtifact.from_json(gzip.decompress(
            (PACKET / "controls" / folder / row["artifact"]).read_bytes()).decode())
        for value, key in ((artifact.tile_ir.encode(), "tile_sha256"),
                           (artifact.target_ir.encode(), "target_sha256"),
                           (artifact.native_image.payload, "ptx_sha256")):
            assert hashlib.sha256(value).hexdigest() == row[key]


@pytest.mark.parametrize("name", ["compiler-route", "device", "unit-final"])
def test_saved_storage_validation_receipts_execute_the_claimed_gate(name):
    # Checked-in pytest receipts generated by this slice; never external XML.
    path = PACKET / "validation" / (name + (".xml.gz" if name == "unit-final" else ".xml"))
    raw = gzip.decompress(path.read_bytes()) if name == "unit-final" else path.read_bytes()
    document = ET.fromstring(raw)  # noqa: S314
    cases = list(document.iter("testcase"))
    assert cases
    assert not any(case.find("failure") is not None or case.find("error") is not None for case in cases)
    if name != "unit-final":
        assert not any(case.find("skipped") is not None for case in cases)
        assert len(cases) == {"compiler-route": 960, "device": 94}[name]
    else:
        witness = json.loads((PACKET / "validation/unit-final-witness.json").read_text())
        assert witness["exit_code"] == 0 and witness["unchanged"] is True
        assert witness["source_before"] == witness["source_after"]
        assert not witness["source_before"]["status"]


def test_saved_storage_authored_fp32_output_is_device_checked():
    rows = json.loads((PACKET / "validation/fp32-output.json").read_text())
    assert len(rows) == 12
    assert {row["storage"] for row in rows} == {"f16", "bf16"}
    assert all(row["output"] == "f32" and max(row["max_abs_error"]) < 5e-5 for row in rows)
